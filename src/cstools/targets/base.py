"""Target protocol, render context and registry.

A target is a pure function from scheme(s) to ``{relative_path: text}``: no file writing, no
environment access and no hard-coded colours.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import ClassVar, Sequence

from .. import __version__
from ..scheme.model import Scheme

SCOPES = ("scheme", "project")


@dataclass(frozen=True)
class RenderContext:
    """Project-level settings passed to every target."""

    project_name: str = ""
    lua_module: str = ""
    url: str = ""
    tools_version: str = __version__

    def header(self, prefix: str, scheme: Scheme | None = None, usage: str | None = None) -> str:
        """Comment banner ending with a newline: description, generated-by notice and optional usage line."""
        lines = []
        if scheme is not None:
            lines.append(f"{scheme.name}: {scheme.description}" if scheme.description else scheme.name)
            lines.append(f"Generated by colorscheme-tools v{self.tools_version} from {scheme.id}/colorschemes.json. "
                         "Do not edit.")
        else:
            lines.append(f"Generated by colorscheme-tools v{self.tools_version}. Do not edit.")
        if usage:
            lines.append(f"Usage: {usage}")
        return "".join(f"{prefix} {line}\n" for line in lines)


class Target:
    """Base class; subclasses set ``name``/``scope`` and implement ``render`` or ``render_project``."""

    name: ClassVar[str] = ""
    scope: ClassVar[str] = "scheme"
    description: ClassVar[str] = ""

    def render(self, scheme: Scheme, ctx: RenderContext) -> dict[str, str]:
        """Files for one scheme (``scope == "scheme"``)."""
        raise NotImplementedError(f"target {self.name!r} does not render single schemes")

    def render_project(self, schemes: Sequence[Scheme], ctx: RenderContext) -> dict[str, str]:
        """Files for all schemes at once (``scope == "project"``)."""
        raise NotImplementedError(f"target {self.name!r} does not render projects")


REGISTRY: dict[str, Target] = {}


def register(cls: type[Target]) -> type[Target]:
    """Class decorator adding one instance of ``cls`` to ``REGISTRY`` under ``cls.name``."""
    if not cls.name:
        raise ValueError(f"{cls.__name__} has no name")
    if cls.scope not in SCOPES:
        raise ValueError(f"{cls.__name__}: scope must be one of {SCOPES}")
    if cls.name in REGISTRY and type(REGISTRY[cls.name]) is not cls:
        raise ValueError(f"target {cls.name!r} registered twice")
    REGISTRY[cls.name] = cls()
    return cls
