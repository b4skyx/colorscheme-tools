"""Targets: registry, header, and alacritty/kitty golden equality with the legacy exporter output."""
import tomllib
import unittest

from cstools import __version__
from cstools.targets import REGISTRY, RenderContext
from support import FIXTURES, SCHEME_IDS, migrated, strip_header


class TargetRegistryTest(unittest.TestCase):
    def test_discovered(self) -> None:
        self.assertIn("alacritty", REGISTRY)
        self.assertIn("kitty", REGISTRY)
        for name, target in REGISTRY.items():
            self.assertEqual(target.name, name)
            self.assertIn(target.scope, ("scheme", "project"))

    def test_header(self) -> None:
        scheme = migrated("haze")
        text = RenderContext().header("#", scheme, "do this")
        self.assertEqual(text.splitlines(), [
            f"# Haze: {scheme.description}",
            f"# Generated by colorscheme-tools v{__version__} from haze/colorschemes.json. Do not edit.",
            "# Usage: do this"])
        self.assertEqual(RenderContext().header("--"), f"-- Generated by colorscheme-tools v{__version__}. Do not edit.\n")


class GoldenTest(unittest.TestCase):
    def render(self, target: str, sid: str) -> tuple[str, str]:
        files = REGISTRY[target].render(migrated(sid), RenderContext(project_name="demo"))
        self.assertEqual(len(files), 1)
        (path, text), = files.items()
        return path, text

    def test_alacritty_matches_golden(self) -> None:
        for sid in SCHEME_IDS:
            with self.subTest(sid):
                path, text = self.render("alacritty", sid)
                self.assertEqual(path, f"{sid}/alacritty.toml")
                golden = (FIXTURES / "golden" / f"{sid}.alacritty.toml").read_text(encoding="utf-8")
                self.assertEqual(strip_header(text), strip_header(golden))
                data = tomllib.loads(text)
                self.assertEqual(set(data), {"colors"})
                self.assertEqual(len(data["colors"]["normal"]), 8)
                self.assertEqual(len(data["colors"]["bright"]), 8)

    def test_kitty_matches_golden(self) -> None:
        for sid in SCHEME_IDS:
            with self.subTest(sid):
                path, text = self.render("kitty", sid)
                self.assertEqual(path, f"{sid}/kitty.conf")
                golden = (FIXTURES / "golden" / f"{sid}.kitty.conf").read_text(encoding="utf-8")
                self.assertEqual(strip_header(text), strip_header(golden))
                keys = {line.split()[0] for line in text.splitlines() if line and not line.startswith("#")}
                self.assertTrue({f"color{i}" for i in range(16)} <= keys)

    def test_neutral_header_wording(self) -> None:
        for target in ("alacritty", "kitty"):
            _, text = self.render(target, "haze")
            header = text[:len(text) - len(strip_header(text))].lower()
            for word in ("favourite", "your", "for you", "clearsight", "nord"):
                self.assertNotIn(word, header)


if __name__ == "__main__":
    unittest.main()


class HeaderPlaceholderTest(unittest.TestCase):
    """Usage lines name the actual scheme instead of <Name>/<id> placeholders."""

    def test_no_placeholders_in_generated_headers(self):
        from cstools.targets import REGISTRY, RenderContext
        from cstools.scheme import io as scheme_io
        from pathlib import Path
        path = Path.home() / "colorblind-lab" / "colorschemes" / "haze" / "colorschemes.json"
        if not path.exists():
            self.skipTest("theme repo not present")
        scheme = scheme_io.load(path)
        ctx = RenderContext(project_name="clearsight", lua_module="clearsight")
        for name, target in REGISTRY.items():
            files = target.render(scheme, ctx) if target.scope == "scheme" else target.render_project([scheme], ctx)
            for rel, text in files.items():
                head = "\n".join(text.splitlines()[:6])
                with self.subTest(target=name, file=rel):
                    self.assertNotIn("<Name>", head)
                    self.assertNotIn("<id>", head)
